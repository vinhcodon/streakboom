// Generates THIRD-PARTY-NOTICES.md: the licenses of the code that is compiled into the Windows build (story CP-4, ADR-0072).
//   node scripts/gen-third-party-notices.mjs          write THIRD-PARTY-NOTICES.md
//   node scripts/gen-third-party-notices.mjs --check   fail (exit 1) when the file is not the one these lock files would produce
//
// MIT, Apache-2.0 and BSD ask that their copyright and license notices travel with a binary. The Rust crates are read from
// `cargo metadata` (the Windows build graph, without our own crate); the license texts are the files found in each crate's own
// source folder (LICENSE*, COPYING*, NOTICE*, UNLICENSE*), grouped so that identical texts are printed once. The header records
// a fingerprint of Cargo.lock and package-lock.json, and `--check` (and scripts/audit-docs.mjs) compares it, so the file cannot
// silently go out of date when a dependency changes. It needs the crates downloaded (a normal `cargo build` does that).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "THIRD-PARTY-NOTICES.md");
const sha = (s) => createHash("sha256").update(s).digest("hex");
const norm = (s) => s.replace(/\r\n/g, "\n");
function lockFingerprint() {
  const cargo = norm(readFileSync(join(root, "app/src-tauri/Cargo.lock"), "utf8"));
  const npm = norm(readFileSync(join(root, "app/package-lock.json"), "utf8"));
  return sha(cargo + "\0" + npm);
}

main();

function main() {
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT)) { console.log("THIRD-PARTY-NOTICES.md does not exist: run node scripts/gen-third-party-notices.mjs"); process.exit(1); }
    const rec = /lock-files-sha256: ([0-9a-f]{64})/.exec(readFileSync(OUT, "utf8"))?.[1] ?? null;
    if (rec !== lockFingerprint()) { console.log("THIRD-PARTY-NOTICES.md is out of date with Cargo.lock or package-lock.json: run node scripts/gen-third-party-notices.mjs"); process.exit(1); }
    console.log("THIRD-PARTY-NOTICES.md matches the lock files.");
    return;
  }

  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--locked", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc"], {
      cwd: join(root, "app/src-tauri"), encoding: "utf8", maxBuffer: 512 * 1024 * 1024,
    }),
  );
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const pkgs = meta.resolve.nodes.map((n) => byId.get(n.id)).filter((p) => p.name !== "streakboom").sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

  const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-_.].*)?$/i;
  /** text -> { text, users: ["name version (license)"] } */
  const groups = new Map();
  const without = [];
  const add = (label, license, dir, repo) => {
    let found = 0;
    for (const f of readdirSync(dir)) {
      if (!LICENSE_FILE.test(f)) continue;
      let text;
      try { text = norm(readFileSync(join(dir, f), "utf8")).trim(); } catch { continue; }
      if (!text) continue;
      found++;
      const key = sha(text);
      if (!groups.has(key)) groups.set(key, { text, users: [] });
      groups.get(key).users.push(`${label} (${license || "no license field"})`);
    }
    if (!found) without.push(`${label} (${license || "no license field"}${repo ? ", source: " + repo : ""})`);
  };
  for (const p of pkgs) add(`${p.name} ${p.version}`, p.license, dirname(p.manifest_path), p.repository);

  // The JavaScript that is compiled into the front end: the Tauri API, the Svelte runtime and the SvelteKit client runtime.
  // (Checked 2026-11-13 with a build with source maps: these three are the only npm packages whose code is in the bundle.)
  const npmRuntime = ["@tauri-apps/api", "svelte", "@sveltejs/kit"];
  for (const name of npmRuntime) {
    const d = join(root, "app/node_modules", name);
    if (!existsSync(join(d, "package.json"))) continue;
    const j = JSON.parse(readFileSync(join(d, "package.json"), "utf8"));
    add(`${name} ${j.version} (npm)`, typeof j.license === "string" ? j.license : j.license?.type, d);
  }

  const lines = [];
  lines.push("# Third-party notices", "");
  lines.push("Streakboom is under the MIT license (`LICENSE`). It is built from the open-source packages listed here, and their license notices follow, as their licenses ask. This file is generated by `scripts/gen-third-party-notices.mjs` and installed next to the program.", "");
  lines.push(`<!-- lock-files-sha256: ${lockFingerprint()} -->`, "");
  lines.push(`**${pkgs.length} Rust packages** (the Windows build graph) and ${npmRuntime.length} JavaScript packages that are compiled into the front end. Each license text is printed once; under it, the packages it comes from.`, "");
  const sorted = [...groups.values()].sort((a, b) => a.users[0].localeCompare(b.users[0]));
  let i = 0;
  for (const g of sorted) {
    i++;
    lines.push(`## ${i}. ${g.users.length === 1 ? g.users[0] : `${g.users[0]} and ${g.users.length - 1} more`}`, "");
    lines.push("Used by: " + g.users.join("; "), "");
    lines.push("```text", g.text, "```", "");
  }
  if (without.length) {
    lines.push("## Packages with no license file in their source", "");
    lines.push("Their license is the one declared in their package metadata (shown in brackets): " + without.join("; "), "");
  }
  writeFileSync(OUT, lines.join("\n") + "\n", "utf8");
  console.log(`wrote ${OUT}: ${pkgs.length} Rust packages, ${groups.size} distinct license texts, ${without.length} without a license file`);
}
